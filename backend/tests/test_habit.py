"""
The weekly habit block built from recorded day doses.

The bundles here are generated by this file with a constant active rate, so
every expected MET-minute is arithmetic done by hand: MET is 1 + AE_rate /
BE_ref.  The recorded basal rate is irrelevant to the dose and is left at a
plain constant.  The tool's own week rule is exercised: seven days present,
five with more than 300 worn minutes.
"""
from datetime import date, timedelta

import pytest

from tools.make_activity_templates import build_habit

BE_KCAL_MIN = 1.0
BE_REF = 1.1
AE_KCAL_MIN = 5.0
MET = 1.0 + AE_KCAL_MIN / BE_REF
DAY_MINUTES = 360
SESSION_MINUTES = 10
SESSION_START = 100
MONDAY = date(2025, 1, 6)


def _bundle(day: date, worn_minutes: int = DAY_MINUTES) -> dict:
    samples = []
    for minute in range(DAY_MINUTES):
        worn = minute < worn_minutes
        samples.append({
            "t": minute * 60,
            "hr": 60.0,
            "hr_n": 1,
            "ae_kcal_min": AE_KCAL_MIN if worn else None,
            "be_kcal_min": BE_KCAL_MIN,
            "steps_min": 0.0,
            "t_app_c": 20.0,
            "rh_pct": 50.0,
            "workout": (
                "Walking"
                if SESSION_START <= minute < SESSION_START + SESSION_MINUTES
                else None
            ),
        })
    return {
        "schema_version": 1,
        "subject": "probe",
        "date": day.isoformat(),
        "timezone": "UTC",
        "grid_s": 60,
        "synthetic": True,
        "samples": samples,
        "day": {"n_minutes": DAY_MINUTES, "hr_level_rts": 60.0},
    }


def _week(start: date = MONDAY, worn_minutes: int = DAY_MINUTES) -> list[dict]:
    return [
        _bundle(start + timedelta(days=index), worn_minutes)
        for index in range(7)
    ]


def test_a_full_worn_week_has_a_hand_computed_total():
    habit = build_habit(_week(), None, "Probe")

    day_total = DAY_MINUTES * MET
    day_in = SESSION_MINUTES * MET
    day_outside = (DAY_MINUTES - SESSION_MINUTES) * MET

    assert habit["unit"] == "MET-h/week"
    assert habit["weeks"] == 1
    assert habit["first_week"] == habit["last_week"] == "2025-W02"
    assert habit["total"] == {
        "p10": pytest.approx(7 * day_total / 60.0, abs=0.01),
        "p50": pytest.approx(7 * day_total / 60.0, abs=0.01),
        "p90": pytest.approx(7 * day_total / 60.0, abs=0.01),
    }
    assert habit["in_sessions"] == {
        "p10": pytest.approx(7 * day_in / 60.0, abs=0.01),
        "p50": pytest.approx(7 * day_in / 60.0, abs=0.01),
        "p90": pytest.approx(7 * day_in / 60.0, abs=0.01),
    }
    assert habit["outside_sessions_per_day"] == {
        "p10": pytest.approx(day_outside, abs=0.01),
        "p50": pytest.approx(day_outside, abs=0.01),
        "p90": pytest.approx(day_outside, abs=0.01),
    }
    assert "2025-01-01" in habit["rule"]
    assert "300" in habit["rule"]


def test_a_week_with_a_missing_day_is_not_counted():
    assert build_habit(_week()[:6], None, "Probe") is None


def test_a_week_with_too_little_wear_is_not_counted():
    days = [
        _bundle(MONDAY + timedelta(days=index), 200 if index < 3 else 360)
        for index in range(7)
    ]
    assert build_habit(days, None, "Probe") is None


def test_no_counted_week_gives_no_habit():
    before = MONDAY - timedelta(days=7)
    assert build_habit(_week(before), None, "Probe") is None
    assert build_habit([], None, "Probe") is None
